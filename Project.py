def extract_nouns_adjectives(text):

    doc = nlp(text)

    words = [
        token.lemma_
        for token in doc
        if token.pos_ in ["NOUN", "ADJ"]
        and token.is_alpha
        and len(token.text) > 2
    ]

    return words

