def clean_text_nltk(text):

    text = text.lower()

    # remove html
    text = re.sub(r"<.*?>", " ", text)

    # keep letters + numbers
    text = re.sub(r"[^a-zA-Z0-9\s]", " ", text)

    # tokenize
    tokens = word_tokenize(text)

    # remove stopwords
    tokens = [
        word for word in tokens
        if word not in stop_words
        and len(word) > 2
    ]

    return " ".join(tokens)

